-- Minimal Supabase schema for the current EgyMeds React Native app.
-- Data is managed from Supabase Dashboard > Table Editor.
-- The app reads this product table and no medical/administration side tables.

CREATE TABLE IF NOT EXISTS public.drugs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    commercial_name_en text NOT NULL DEFAULT '',
    commercial_name_ar text NOT NULL DEFAULT '',
    scientific_name text NOT NULL DEFAULT '',
    manufacturer text NOT NULL DEFAULT '',
    description text,
    "use" text,
    price_egp numeric,
    price_old_egp numeric,
    price_updated_at timestamptz,
    product_type text CHECK (
        product_type IS NULL OR
        product_type = ANY (ARRAY['MEDICINE','COSMETIC','SUPPLEMENT','MEDICAL_DEVICE','OTHER'])
    )
);

ALTER TABLE public.drugs ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.drugs FROM PUBLIC, anon, authenticated;
GRANT SELECT ON TABLE public.drugs TO anon, authenticated;

DROP POLICY IF EXISTS "Anyone can read drugs" ON public.drugs;
CREATE POLICY "Anyone can read drugs"
    ON public.drugs
    FOR SELECT
    TO anon, authenticated
    USING (true);

CREATE OR REPLACE FUNCTION public.set_drug_price_updated_at()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $function$
BEGIN
    IF TG_OP = 'INSERT' THEN
        IF NEW.price_egp IS NOT NULL AND NEW.price_updated_at IS NULL THEN
            NEW.price_updated_at := now();
        END IF;
    ELSIF NEW.price_egp IS DISTINCT FROM OLD.price_egp THEN
        NEW.price_updated_at := now();
    END IF;
    RETURN NEW;
END;
$function$;

REVOKE ALL ON FUNCTION public.set_drug_price_updated_at() FROM PUBLIC, anon, authenticated;
DROP TRIGGER IF EXISTS set_drug_price_updated_at ON public.drugs;
CREATE TRIGGER set_drug_price_updated_at
    BEFORE INSERT OR UPDATE OF price_egp ON public.drugs
    FOR EACH ROW
    EXECUTE FUNCTION public.set_drug_price_updated_at();
