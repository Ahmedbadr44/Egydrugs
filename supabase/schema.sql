create table if not exists public.drugs (
    id bigint generated by default as identity primary key,
    commercial_name_en text not null default '',
    commercial_name_ar text not null default '',
    scientific_name text not null default '',
    manufacturer text not null default '',
    drug_class text not null default '',
    route text not null default '',
    price_egp numeric,
    dosage text not null default '',
    updated_at timestamptz not null default now()
);

create table if not exists public.drug_data_version (
    id smallint primary key check (id = 1),
    version bigint not null default 0,
    updated_at timestamptz not null default now()
);

insert into public.drug_data_version (id, version)
values (1, 0)
on conflict (id) do nothing;

alter table public.drugs enable row level security;
alter table public.drug_data_version enable row level security;

revoke all on public.drugs from public, anon, authenticated;
grant select on public.drugs to anon, authenticated;
grant select on public.drug_data_version to anon, authenticated;
revoke insert, update, delete on public.drug_data_version from public, anon, authenticated;

drop policy if exists "Anyone can read drug data version" on public.drug_data_version;
create policy "Anyone can read drug data version"
    on public.drug_data_version for select
    to anon, authenticated
    using (true);

drop policy if exists "Anyone can read drugs" on public.drugs;
create policy "Anyone can read drugs"
    on public.drugs for select
    to anon, authenticated
    using (true);

create or replace function public.set_drug_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
    new.updated_at = now();
    return new;
end;
$$;

revoke all on function public.set_drug_updated_at() from public, anon, authenticated;

drop trigger if exists set_drug_updated_at on public.drugs;
create trigger set_drug_updated_at
    before update on public.drugs
    for each row execute function public.set_drug_updated_at();

create or replace function public.bump_drug_data_version()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
    update public.drug_data_version
    set version = version + 1, updated_at = now()
    where id = 1;
    return null;
end;
$$;

revoke all on function public.bump_drug_data_version() from public, anon, authenticated;

drop trigger if exists bump_drug_data_version on public.drugs;
create trigger bump_drug_data_version
    after insert or update or delete on public.drugs
    for each statement execute function public.bump_drug_data_version();
