-- openFDA enrichment infrastructure for Egydrugs.
-- Keeps synchronization state separate from the user-facing medical content.

create table if not exists public.drug_medical_sync (
    id bigint generated by default as identity primary key,
    drug_id bigint not null references public.drugs(id) on delete cascade,
    provider text not null default 'openFDA',
    status text not null default 'pending',
    query_used text,
    matched_set_id text,
    matched_version text,
    matched_brand_name text,
    matched_generic_name text,
    matched_manufacturer text,
    match_score numeric(5,3),
    last_error text,
    attempts integer not null default 0,
    fetched_at timestamptz,
    updated_at timestamptz not null default now(),
    constraint drug_medical_sync_status_check
        check (status in ('pending', 'running', 'success', 'no_match', 'error', 'needs_review')),
    constraint drug_medical_sync_match_score_check
        check (match_score is null or (match_score >= 0 and match_score <= 1)),
    constraint drug_medical_sync_attempts_check
        check (attempts >= 0),
    constraint drug_medical_sync_provider_drug_unique
        unique (provider, drug_id)
);

create index if not exists idx_drug_medical_sync_status_updated
    on public.drug_medical_sync(status, updated_at asc);

create index if not exists idx_drug_medical_sync_drug_id
    on public.drug_medical_sync(drug_id);

alter table public.drug_medical_sync enable row level security;

revoke all on public.drug_medical_sync from public, anon, authenticated;
grant select on public.drug_medical_sync to anon, authenticated;
grant insert, update, delete on public.drug_medical_sync to authenticated;

drop policy if exists "Anyone can read medical sync state" on public.drug_medical_sync;
create policy "Anyone can read medical sync state"
    on public.drug_medical_sync for select
    to anon, authenticated
    using (true);

drop policy if exists "Admins can insert medical sync state" on public.drug_medical_sync;
create policy "Admins can insert medical sync state"
    on public.drug_medical_sync for insert
    to authenticated
    with check ((select private.is_drug_admin()));

drop policy if exists "Admins can update medical sync state" on public.drug_medical_sync;
create policy "Admins can update medical sync state"
    on public.drug_medical_sync for update
    to authenticated
    using ((select private.is_drug_admin()))
    with check ((select private.is_drug_admin()));

drop policy if exists "Admins can delete medical sync state" on public.drug_medical_sync;
create policy "Admins can delete medical sync state"
    on public.drug_medical_sync for delete
    to authenticated
    using ((select private.is_drug_admin()));

create or replace function public.set_drug_medical_sync_updated_at()
returns trigger
language plpgsql
as $$
begin
    new.updated_at = now();
    return new;
end;
$$;

drop trigger if exists drug_medical_sync_updated_at on public.drug_medical_sync;
create trigger drug_medical_sync_updated_at
before update on public.drug_medical_sync
for each row execute function public.set_drug_medical_sync_updated_at();

-- Queue every current drug exactly once. This is intentionally idempotent.
insert into public.drug_medical_sync (drug_id, provider, status)
select d.id, 'openFDA', 'pending'
from public.drugs d
on conflict (provider, drug_id) do nothing;
